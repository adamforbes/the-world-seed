  // A line glyph joining the cell centre to the named neighbours (N, NE, E,
  // SE, S, SW, W, NW), `width` pixels thick. Used for roots, branches, pipes.
  const DIRS = { N: [0, -1], NE: [1, -1], E: [1, 0], SE: [1, 1], S: [0, 1], SW: [-1, 1], W: [-1, 0], NW: [-1, -1] };
  function connector(dirs, width = 2) {
    const name = 'link:' + width + ':' + [...dirs].sort().join(',');
    if (GLYPHS[name]) return name;
    const px = Array.from({ length: GH }, () => Array(GW).fill('.'));
    const cx = GW / 2, cy = GH / 2;
    const brush = (x, y) => {
      for (let j = 0; j < width; j++) for (let i = 0; i < width; i++) {
        const xi = Math.floor(x - width / 2 + i + 0.5), yi = Math.floor(y - width / 2 + j + 0.5);
        if (xi >= 0 && yi >= 0 && xi < GW && yi < GH) px[yi][xi] = '#';
      }
    };
    brush(cx, cy);
    for (const d of dirs) {
      const [dx, dy] = DIRS[d];
      for (let k = 0; k <= 24; k++) brush(cx + (dx * GW / 2) * (k / 24), cy + (dy * GH / 2) * (k / 24));
    }
    GLYPHS[name] = px.map((row) => row.join(''));
    return name;
  }
  const dirTo = (dc, dr) => Object.keys(DIRS).find((k) => DIRS[k][0] === Math.sign(dc) && DIRS[k][1] === Math.sign(dr));

  const sprites = new Map();
  function sprite(name, fg, dt) {
    const key = name + fg + dt;
    if (!sprites.has(key)) {
      const c = document.createElement('canvas');
      c.width = GW; c.height = GH;
      const x = c.getContext('2d');
      GLYPHS[name].forEach((row, j) => [...row].forEach((ch, i) => {
        if (ch === '.') return;
        x.fillStyle = ch === 'd' ? dt : fg;
        x.fillRect(i, j, 1, 1);
      }));
      sprites.set(key, c);
    }
    return sprites.get(key);
  }

  // A cell grid. Keep cw/ch and the offsets even so chroma lines up in video.
  function grid({ cols, rows, ox, oy, cw = 16, ch = 24 }) {
    const centre = (c, r) => [ox + c * cw + cw / 2, oy + r * ch + ch / 2];
    const cellOf = (x, y) => [Math.floor((x - ox) / cw), Math.floor((y - oy) / ch)];

    // Draw one cell. Colours are palette keys; `flip` mirrors the glyph.
    function put(ctx, P, c, r, { g, fg, dt, bg, alpha = 1, flip = false }) {
      if (c < 0 || r < 0 || c >= cols || r >= rows) return;
      const x = ox + c * cw, y = oy + r * ch;
      ctx.globalAlpha = alpha;
      if (bg) { ctx.fillStyle = P[bg] || bg; ctx.fillRect(x, y, cw, ch); }
      if (g) {
        const img = sprite(g, P[fg], P[dt || fg]);
        if (flip) {
          ctx.save();
          ctx.translate(x + cw, y);
          ctx.scale(-1, 1);
          ctx.drawImage(img, 0, 0, cw, ch);
          ctx.restore();
        } else ctx.drawImage(img, x, y, cw, ch);
      }
      ctx.globalAlpha = 1;
    }

    // A contiguous chain of cells along a list of points.
    function cellPath(pts) {
      const out = [];
      for (let i = 0; i < pts.length - 1; i++) {
        const [x0, y0] = pts[i], [x1, y1] = pts[i + 1];
        const n = Math.ceil(Math.hypot(x1 - x0, y1 - y0) / 4);
        for (let k = 0; k <= n; k++) {
          const [c, r] = cellOf(lerp(x0, x1, k / n), lerp(y0, y1, k / n));
          const last = out[out.length - 1];
          if (!last || last[0] !== c || last[1] !== r) out.push([c, r]);
        }
      }
      return out;
    }

    // The same chain for a closed loop, without a repeated first cell.
    function loopPath(pts) {
      const path = cellPath(pts);
      if (path.length > 1 && path[0].join() === path[path.length - 1].join()) path.pop();
      return path;
    }

    return { cols, rows, ox, oy, cw, ch, centre, cellOf, put, cellPath, loopPath };
  }

  const rnd = (...k) => (hash(...k) % 100003) / 100003;
  function noise(seed, scale) {
    const v = (i, j) => rnd(seed, i, j);
    return (x, y) => {
      x /= scale; y /= scale;
      const i = Math.floor(x), j = Math.floor(y), fx = smooth(x - i), fy = smooth(y - j);
      return lerp(lerp(v(i, j), v(i + 1, j), fx), lerp(v(i, j + 1), v(i + 1, j + 1), fx), fy);
    };
  }

